"""
reader.py — Acoustic QAM Demodulator
======================================
Decodes frames produced by Modulator (writer.py).

Key changes from v1
--------------------
  - Zadoff-Chu matched-filter sync
      Cross-correlate symbol stream with conj(ZC)reversed.
      Cauchy-Schwarz normalised → threshold is SNR-independent.
      Multipath produces secondary peaks well below primary → single
      clean frame boundary even in reverberant rooms.
      Phase of peak directly bootstraps carrier phase — no 180° ambiguity.

  - Pilot-aided phase tracking
      After bulk ZC phase correction, residual oscillator wander is measured
      at each pilot, unwrapped, and interpolated piecewise-linearly across
      the frame.  Replaces the symbol-by-symbol Costas PLL which fought with
      16-QAM's inner ring at low SNR.

  - Proper symbol-rate pipeline
      demod_to_symbols() returns one complex sample per symbol after
      RRC matched filter + decimation.  The ZC correlator and decode_frame()
      both operate at symbol rate, keeping maths cheap and indices clean.

  - Class structure
      Import Demodulator in test/analysis scripts; inspect .received, call
      demod_to_symbols() or find_frames() directly for unit testing.
"""

from __future__ import annotations

import argparse
import json
import math
import sys
import threading
import time
from collections import defaultdict

import numpy as np
from scipy.signal import firwin, fftconvolve, resample_poly
from scipy.io import wavfile
from reedsolo import RSCodec

try:
    import sounddevice as sd
    HAS_SOUNDDEVICE = True
except ImportError:
    HAS_SOUNDDEVICE = False


# ---------------------------------------------------------------------------
# Demodulator
# ---------------------------------------------------------------------------

class Demodulator:
    """
    Decode WAV files or live audio produced by Modulator.

    Usage
    -----
        demod = Demodulator("config.json")

        # From file:
        text = demod.process_wav("output.wav")

        # From microphone:
        text = demod.listen_live(timeout=30.0)

        # Low-level (useful for tests):
        syms   = demod.demod_to_symbols(audio_int16)
        frames = demod.find_frames(syms)          # → [pos, …]
        result = demod.decode_frame(syms, pos)    # → (seq, data, errs) | None

        # Inspect recovered chunks after processing:
        print(demod.received)   # {seq_num: bytes, …}

    Tunable class attributes (override on instance before processing)
    -----------------------------------------------------------------
    ZC_THRESHOLD  : Normalised correlation threshold for frame detection.
                    Range ≈ 0.3–0.7.  Lower = more false positives,
                    higher = misses at low SNR.
    POWER_GATE    : Block RMS (as fraction of scale_factor) below which the
                    block is skipped as silence.
    """

    RRC_SPAN:     int   = 6
    PRBS_SEED:    int   = 0xACE1
    ZC_THRESHOLD: float = 0.45
    POWER_GATE:   float = 0.002

    _CONSTELLATION: dict[tuple, complex] = {
        (0,0,0,0): -3-3j, (0,0,0,1): -3-1j, (0,0,1,1): -3+1j, (0,0,1,0): -3+3j,
        (0,1,1,0): -1+3j, (0,1,1,1): -1+1j, (0,1,0,1): -1-1j, (0,1,0,0): -1-3j,
        (1,1,0,0):  1-3j, (1,1,0,1):  1-1j, (1,1,1,1):  1+1j, (1,1,1,0):  1+3j,
        (1,0,1,0):  3+3j, (1,0,1,1):  3+1j, (1,0,0,1):  3-1j, (1,0,0,0):  3-3j,
    }

    def __init__(self, config_path: str = "config.json") -> None:
        with open(config_path) as f:
            cfg = json.load(f)

        self.CHUNK_BYTES:  int   = cfg["CHUNK_BYTES"]
        self.ECC_BYTES:    int   = cfg["ECC_BYTES"]
        self.SEQ_BYTES:    int   = cfg.get("SEQ_BYTES", 2)
        self.sample_rate:  int   = cfg["sample_rate"]
        self.carrier_freq: int   = cfg["carrier_freq"]
        self.symbol_rate:  int   = cfg["symbol_rate"]
        self.RRC_BETA:     float = cfg["RRC_BETA"]
        self.scale_factor: float = cfg["scale_factor"]
        self.total_frames: int | None = cfg.get("total_frames")

        # --- Sync: Zadoff-Chu ---
        self.ZC_LENGTH: int = cfg.get("ZC_LENGTH", 63)
        self.ZC_ROOT:   int = cfg.get("ZC_ROOT", 25)

        # --- Phase tracking: pilots ---
        self.PILOT_INTERVAL: int = cfg.get("PILOT_INTERVAL", 8)
        self.PILOT_SYMBOL: complex = complex(
            cfg.get("PILOT_SYMBOL_RE", 1.0 / math.sqrt(2)),
            cfg.get("PILOT_SYMBOL_IM", 1.0 / math.sqrt(2)),
        )

        self.samples_per_symbol: int = self.sample_rate // self.symbol_rate

        # Build preamble — ZC preferred; fall back to legacy BPSK if config
        # was generated by the old writer (has preamble_bits, no ZC_LENGTH).
        if "ZC_LENGTH" in cfg:
            self.preamble_syms = self._make_zadoff_chu(self.ZC_LENGTH, self.ZC_ROOT)
        elif "preamble_bits" in cfg:
            pbits = np.array(cfg["preamble_bits"])
            self.preamble_syms = np.array([1+1j if b else -1-1j for b in pbits]) / math.sqrt(2)
        else:
            self.preamble_syms = self._make_zadoff_chu(63, 25)

        self.n_pre: int = len(self.preamble_syms)

        # Matched-filter kernel: time-reversed conjugate of preamble
        # fftconvolve(x, kernel, 'valid') = cross-correlation of x with preamble
        self._zc_kernel: np.ndarray = np.conj(self.preamble_syms[::-1])

        # Frame geometry
        self._raw_data_syms: int = (self.SEQ_BYTES + self.CHUNK_BYTES + self.ECC_BYTES) * 2
        self.frame_syms_with_pilots: int = cfg.get(
            "frame_syms_with_pilots",
            self._raw_data_syms + math.ceil(self._raw_data_syms / self.PILOT_INTERVAL),
        )

        # Precompute pilot positions — must match Modulator.insert_pilots() exactly
        self._pilot_positions: list[int] = self._compute_pilot_positions()

        # Frame dimensions in samples (used for block sizing)
        self._frame_total_syms: int    = self.n_pre + self.frame_syms_with_pilots
        self.FRAME_SAMPLES:     int    = self._frame_total_syms * self.samples_per_symbol
        self.BLOCK_SAMPLES:     int    = self.FRAME_SAMPLES * 4   # ~4 frames per block
        self.STEP_SAMPLES:      int    = self.FRAME_SAMPLES * 2   # 50 % overlap

        # Constellation lookup tables
        self._const_points = np.array(list(self._CONSTELLATION.values()), dtype=complex)
        self._const_keys   = list(self._CONSTELLATION.keys())

        # Filters
        self.rrc = self._rrc_filter(self.RRC_BETA, self.RRC_SPAN, self.samples_per_symbol)
        self.lpf = firwin(
            numtaps=101,
            cutoff=self.symbol_rate * (1 + self.RRC_BETA) / 2 * 1.1,
            fs=self.sample_rate,
        )

        self.rsc = RSCodec(self.ECC_BYTES)

        # Bitrates — computed once from config, shown on the live meter.
        #
        #   gross_bps  : raw channel rate, every symbol slot at 4 bits (16-QAM).
        #                Ignores preamble and pilot overhead.
        #   coded_bps  : (SEQ + CHUNK + ECC) bytes per frame / frame duration.
        #                What actually moves over the channel after preamble and
        #                pilot slots are accounted for.
        #   net_bps    : CHUNK bytes per frame / frame duration.
        #                Pure payload throughput after ECC and sequence overhead.
        frame_duration     = self._frame_total_syms / self.symbol_rate   # seconds
        self.gross_bps: int = self.symbol_rate * 4
        self.coded_bps: int = round(
            (self.SEQ_BYTES + self.CHUNK_BYTES + self.ECC_BYTES) * 8 / frame_duration
        )
        self.net_bps:   int = round(self.CHUNK_BYTES * 8 / frame_duration)

        # Output state — populated during process_wav / listen_live
        self.received:       dict[int, bytes] = {}
        self._frame_stats:   list[dict]       = []
        self._stats_out:     str | None       = None
        self._last_diag:     dict             = {}   # set by decode_frame

    # ------------------------------------------------------------------
    # Public API
    # ------------------------------------------------------------------

    def process_wav(self, filename: str) -> str:
        """
        Decode a WAV file.

        Returns the recovered UTF-8 string.
        Decoded chunks are also stored in self.received for inspection.

        The entire file is demodulated in one pass — no windowing.  Windowed
        processing was dropping the final frame(s): with STEP = 2×frame and
        BLOCK = 4×frame, the last block ends exactly at the boundary of the
        last frame, leaving it unreachable.
        """
        sr, audio = wavfile.read(filename)
        if audio.ndim > 1:
            audio = audio[:, 0]
        if sr != self.sample_rate:
            from math import gcd
            g     = gcd(sr, self.sample_rate)
            audio = resample_poly(audio, self.sample_rate // g, sr // g).astype(np.int16)

        # Power gate on the whole file (skip truly silent recordings)
        rms = np.sqrt(np.mean(audio.astype(np.float32) ** 2)) / self.scale_factor
        if rms < self.POWER_GATE:
            print("process_wav: audio too quiet — check volume / POWER_GATE")
            return ""

        self.received = {}
        syms = self.demod_to_symbols(audio)

        found   = 0
        decoded = 0
        for pos in self.find_frames(syms):
            found += 1
            result = self.decode_frame(syms, pos)
            if result is not None:
                seq, data, _errs = result
                decoded += 1
                if seq not in self.received:
                    self.received[seq] = data
                    self._emit_frame_stat(seq, _errs)

        total = self.total_frames or "?"
        print(f"Frames detected: {found}  |  RS-decoded: {decoded}  |  unique: {len(self.received)}/{total}")
        if self._stats_out:
            self._write_stats()
        return self._reassemble()

    def listen_live(self, device=None, timeout: float = 30.0, mic_gain_db: float = 0.0) -> str:
        """
        Record from microphone and decode in real time.

        Parameters
        ----------
        device      : sounddevice device index (None = system default).
        timeout     : Idle timeout — stops when no new frame arrives for this
                      many seconds (resets on each successful decode).
        mic_gain_db : Extra digital gain applied to mic input before AGC, in dB.
                      Use this when the mic signal is too quiet (e.g. −45 dB).
                      20 dB ≈ 10×, 40 dB ≈ 100×.  AGC still runs after this,
                      so the value doesn't need to be exact — just enough to
                      lift the signal above the noise floor.

        Returns recovered UTF-8 string (may be partial if timeout fires first).

        Live output
        -----------
        A mic-level bar is redrawn on the same terminal line every 100 ms:

            MIC [████████░░░░░░░░░░░░]  38%  |  frames: 0/5

        When a frame decodes successfully the meter line is cleared and the
        chunk text is printed on its own line, then the meter resumes:

            ✓ frame 1/5  (+0 errs): "Hello, wor"
            MIC [████████░░░░░░░░░░░░]  38%  |  frames: 1/5
        """
        if not HAS_SOUNDDEVICE:
            raise RuntimeError("sounddevice not installed — pip install sounddevice")

        self.received = {}
        buf            = np.array([], dtype=np.float32)
        buf_lock       = threading.Lock()
        stop_evt       = threading.Event()
        print_lock     = threading.Lock()

        # Shared state written by audio thread, read by display + process threads.
        latest_rms     = [0.0]   # current mic level (fraction of scale_factor)
        meter_active   = [True]  # set False when shutting down to stop meter redraws
        last_frame_time = [0.0]  # time.monotonic() of most recent successful decode

        # ------------------------------------------------------------------
        # Audio callback — runs on sounddevice's high-priority thread.
        # Keep it minimal: just enqueue samples and update the level.
        #
        # Store raw float32 [-1, 1] directly — no int16 round-trip.
        # Converting to int16 here wastes dynamic range: a quiet mic signal
        # at 5% of full scale gets only ~11 effective bits, and that extra
        # quantisation noise degrades the ZC correlation.  Staying float
        # preserves the full ADC resolution all the way to the demodulator.
        # ------------------------------------------------------------------
        # Pre-AGC digital gain from mic_gain_db argument.
        # Applied in the audio callback so the power gate and AGC both see
        # the boosted signal.  Clipped to [-1, 1] to prevent float overflow
        # downstream (the signal is already normalised by scale_factor later).
        _mic_gain_linear = 10.0 ** (mic_gain_db / 20.0)
        # Relax the power gate proportionally so boosted quiet signals aren't
        # still rejected.  Floor at 1e-4 to avoid false triggers on pure noise.
        _live_power_gate = max(self.POWER_GATE / _mic_gain_linear, 1e-4)

        def _audio_callback(indata, frames, time_info, status):
            raw = indata[:, 0].copy()                       # float32, [-1, 1]
            if _mic_gain_linear != 1.0:
                raw = np.clip(raw * _mic_gain_linear, -1.0, 1.0)
            latest_rms[0] = float(np.sqrt(np.mean(raw ** 2)))
            with buf_lock:
                nonlocal buf
                buf = np.concatenate([buf, raw])

        # ------------------------------------------------------------------
        # Display thread — redraws the mic-level bar every 100 ms.
        # Uses \r so that decoded-chunk lines (printed by _process_loop) can
        # scroll past cleanly.
        # ------------------------------------------------------------------
        BAR_WIDTH = 20
        DB_FLOOR  = -60.0   # shown as empty
        DB_CEIL   =   0.0   # shown as full

        def _display_loop():
            while not stop_evt.is_set():
                time.sleep(0.10)
                if not meter_active[0]:
                    break
                rms    = latest_rms[0]
                db     = 20.0 * math.log10(rms + 1e-9)
                frac   = max(0.0, min(1.0, (db - DB_FLOOR) / (DB_CEIL - DB_FLOOR)))
                filled = int(frac * BAR_WIDTH)
                bar    = "█" * filled + "░" * (BAR_WIDTH - filled)
                total  = self.total_frames or "?"
                n_dec  = len(self.received)
                line   = (
                    f"  MIC [{bar}] {db:+.1f} dB  |  frames: {n_dec}/{total}"
                    f"  |  {self.net_bps} / {self.coded_bps} / {self.gross_bps} bps"
                    f"  (net/coded/gross)   "
                )
                with print_lock:
                    if sys.stdout.isatty():
                        sys.stdout.write("\r" + line)
                        sys.stdout.flush()

        # ------------------------------------------------------------------
        # Process thread — demodulates blocks and prints decoded chunks.
        #
        # Input AGC
        # ---------
        # The modulator produced audio at amplitude ~scale_factor in int16
        # terms.  The mic captures whatever fraction survives the room.
        # demod_to_symbols divides by scale_factor, so to get a normalised
        # signal it needs to receive data in that same amplitude range.
        #
        # We measure the block RMS, apply a capped gain to bring it to a
        # fixed target fraction of scale_factor, then pass float32 (no int16
        # cast — avoids the quantisation noise that kills weak signals).
        #
        # The ZC correlator is theoretically amplitude-independent (Cauchy-
        # Schwarz normalised), but in practice a weak signal buried near the
        # quantisation floor raises the noise floor of norm_mag and hides
        # peaks.  AGC + float path fixes both.
        #
        # ZC_THRESHOLD is also relaxed slightly vs the WAV default (0.45)
        # because live room acoustics add multipath that spreads the peak.
        # ------------------------------------------------------------------
        AGC_TARGET   = 0.25    # target RMS in [-1, 1] float units
        AGC_MAX_GAIN = 60.0    # hard cap — don't amplify pure noise into garbage

        def _process_loop():
            nonlocal buf
            while not stop_evt.is_set():
                do_work = False
                with buf_lock:
                    if len(buf) >= self.BLOCK_SAMPLES:
                        raw_block = buf[: self.BLOCK_SAMPLES].copy()   # float32 [-1,1]
                        buf       = buf[self.STEP_SAMPLES :]
                        do_work   = True

                if not do_work:
                    time.sleep(0.01)
                    continue

                # Power gate: compare against the gain-adjusted threshold.
                rms = float(np.sqrt(np.mean(raw_block ** 2)))
                if rms < _live_power_gate:
                    continue

                # Input AGC: bring signal to AGC_TARGET RMS so demod_to_symbols
                # (which divides by scale_factor) receives a consistently
                # normalised signal regardless of mic gain or room attenuation.
                gain      = min(AGC_TARGET / (rms + 1e-9), AGC_MAX_GAIN)
                agc_audio = (raw_block * gain * self.scale_factor).astype(np.float32)
                agc_gain_db = round(20 * math.log10(gain + 1e-10), 1)
                input_rms_db = round(20 * math.log10(rms + 1e-10), 1)

                # Per-frame timing search: returns one (sym_window, 0) pair per
                # detected frame, each decimated at the correct phase for that
                # specific frame.  This handles blocks containing frames at
                # different timing phases (gaps in transmission, block boundary
                # misalignment, etc).
                for syms, pos in self._best_timing_syms(agc_audio):
                    result = self.decode_frame(syms, pos)
                    if result is not None:
                        seq, data, errs = result
                        if seq not in self.received:
                            self.received[seq] = data
                            self._emit_frame_stat(seq, errs,
                                agc_gain_db=agc_gain_db,
                                input_rms_db=input_rms_db)
                            last_frame_time[0] = time.monotonic()
                            total   = self.total_frames or "?"
                            preview = data.rstrip(b"\x00").decode("utf-8", errors="replace")
                            line    = (
                                f"  \u2713 frame {seq + 1}/{total}"
                                f"  (+{errs} errs): \"{preview}\""
                            )
                            with print_lock:
                                if sys.stdout.isatty():
                                    sys.stdout.write("\r" + " " * 60 + "\r")
                                print(line)
                                sys.stdout.flush()

                            if self.total_frames and len(self.received) >= self.total_frames:
                                stop_evt.set()

        # ------------------------------------------------------------------
        # Start threads, open stream, wait.
        # ------------------------------------------------------------------
        display = threading.Thread(target=_display_loop, daemon=True)
        proc    = threading.Thread(target=_process_loop, daemon=True)
        display.start()
        proc.start()

        with sd.InputStream(
            samplerate=self.sample_rate,
            channels=1,
            dtype="float32",
            device=device,
            callback=_audio_callback,
        ):
            print(f"Listening… (idle timeout {timeout:.0f} s after last frame,  Ctrl-C to stop early)")
            last_frame_time[0] = time.monotonic()   # start the clock
            try:
                while not stop_evt.is_set():
                    time.sleep(0.25)
                    idle = time.monotonic() - last_frame_time[0]
                    if idle >= timeout:
                        break
            except KeyboardInterrupt:
                pass

        stop_evt.set()
        meter_active[0] = False
        if sys.stdout.isatty():
            sys.stdout.write("\r" + " " * 60 + "\r")
            sys.stdout.flush()
        proc.join(timeout=2.0)
        display.join(timeout=0.5)
        print(f"Decoded {len(self.received)}/{self.total_frames or '?'} frames")
        return self._reassemble()

    def demod_to_symbols(self, audio: np.ndarray, timing_offset: int = 0) -> np.ndarray:
        """
        Demodulate an audio block -> complex symbol stream (1 sample/symbol).

        audio may be int16 or float32; amplitude is normalised by scale_factor.
        timing_offset (0..sps-1) shifts the decimation grid; default 0 is
        correct for WAV files. Use _best_timing_syms() for live audio where
        the correct offset is unknown.
        """
        mf = self._baseband_mf(audio)
        rrc_delay = self.RRC_SPAN * self.samples_per_symbol
        return mf[rrc_delay + timing_offset :: self.samples_per_symbol]

    def _baseband_mf(self, audio: np.ndarray) -> np.ndarray:
        """
        Mix to baseband, low-pass filter, RRC matched filter.

        Returns the complex MF output at *sample* rate (NOT decimated).
        Factored out of demod_to_symbols so _best_timing_syms can call it
        once and try every decimation phase without repeating the heavy work.
        """
        x = audio.astype(np.float32) / self.scale_factor
        t = np.arange(len(x)) / self.sample_rate

        i_bb = x *  np.cos(2 * np.pi * self.carrier_freq * t)
        q_bb = x * -np.sin(2 * np.pi * self.carrier_freq * t)

        i_f = np.convolve(i_bb, self.lpf, mode="same") * 2.0
        q_f = np.convolve(q_bb, self.lpf, mode="same") * 2.0
        bb  = i_f + 1j * q_f

        return fftconvolve(bb, self.rrc)

    def _best_timing_syms(self, audio: np.ndarray) -> list:
        """
        Per-frame timing search for live audio.

        Problem with a single global timing offset
        ------------------------------------------
        Picking one timing offset for an entire block fails when the block
        contains multiple frames whose symbol clocks arrived at different
        sample phases (e.g. after a gap in transmission, or due to block
        boundaries not aligning with frame boundaries).  The single "best"
        offset correctly decodes whichever frame has the highest ZC peak
        but uses the wrong phase for every other frame in the block.

        Algorithm
        ---------
        1. Compute the MF output once at sample rate.
        2. Try every decimation phase 0..sps-1.  For each, run the ZC
           correlator and collect all peaks above ZC_THRESHOLD, recording
           (sample_position, sym_position, timing_offset, peak_value).
        3. Greedily deduplicate: sort by peak value descending; suppress
           any candidate within ±frame_total_syms * sps samples of an
           already-accepted one (same frame found at multiple offsets).
        4. For each accepted (timing_offset, sym_pos) pair, build the
           symbol stream for just that frame — a window of
           frame_total_syms symbols starting at sym_pos — using the
           correct phase for that specific frame.

        Returns a list of (sym_window, frame_start=0) pairs, one per
        detected frame.  The caller unpacks and calls decode_frame(syms, 0).
        """
        sps       = self.samples_per_symbol
        N         = self.n_pre
        rrc_delay = self.RRC_SPAN * sps
        frame_len = self._frame_total_syms   # symbols per complete frame

        mf = self._baseband_mf(audio)        # computed once

        # ── Step 1: collect all peaks across all timing phases ────────────
        # Each entry: (peak_value, sample_pos, t_off, sym_pos)
        # sample_pos = approximate start of ZC in sample domain (for dedup)
        all_peaks: list[tuple] = []

        for t_off in range(sps):
            syms = mf[rrc_delay + t_off :: sps]
            if len(syms) < N:
                continue

            corr   = fftconvolve(syms, self._zc_kernel, mode="valid")
            energy = fftconvolve(np.abs(syms) ** 2, np.ones(N), mode="valid")
            norm   = np.abs(corr) / (np.sqrt(energy * N) + 1e-10)

            # Find all peaks above threshold in this timing-offset stream
            remaining = norm.copy()
            while True:
                idx = int(np.argmax(remaining))
                if remaining[idx] < self.ZC_THRESHOLD:
                    break
                sample_pos = (idx * sps) + t_off   # back to sample domain
                all_peaks.append((float(remaining[idx]), sample_pos, t_off, idx))
                lo = max(0, idx - N)
                hi = min(len(remaining), idx + N)
                remaining[lo:hi] = 0.0

        if not all_peaks:
            return []

        # ── Step 2: deduplicate across timing phases ───────────────────────
        # Sort strongest first; suppress within ±half a frame in sample domain
        all_peaks.sort(key=lambda x: x[0], reverse=True)
        suppress_samples = (frame_len * sps) // 2
        accepted: list[tuple] = []
        used_positions: list[int] = []

        for peak_val, sample_pos, t_off, sym_pos in all_peaks:
            too_close = any(
                abs(sample_pos - u) < suppress_samples for u in used_positions
            )
            if not too_close:
                accepted.append((t_off, sym_pos))
                used_positions.append(sample_pos)

        # ── Step 3: build a per-frame symbol window for each accepted peak ─
        results: list[tuple] = []
        for t_off, sym_pos in accepted:
            syms = mf[rrc_delay + t_off :: sps]
            end  = sym_pos + frame_len
            if end > len(syms):
                continue
            results.append((syms[sym_pos : end], 0))

        return results

    def find_frames(self, sym_stream: np.ndarray) -> list[int]:
        """
        ZC matched-filter correlator.  Returns frame-start positions (symbol indices).

        Algorithm
        ---------
        corr[m]      = Σ_k  x[m+k] · conj(ZC[k])          (matched filter)
        norm_mag[m]  = |corr[m]| / sqrt(energy_x[m] · N)  (Cauchy-Schwarz, ∈ [0,1])

        Peaks above ZC_THRESHOLD are accepted greedily, suppressing a window of
        ±(n_pre + frame_syms_with_pilots) to reject multipath echoes and prevent
        double-detection of the same frame.

        Noise floor of norm_mag ≈ 1/√N ≈ 0.126 for N=63.
        Perfect match → 1.0.  Threshold at 0.45 sits well between the two.

        Exposed for unit testing.
        """
        N = self.n_pre
        if len(sym_stream) < N:
            return []

        # Matched filter via FFT convolution (O(L log L))
        corr = fftconvolve(sym_stream, self._zc_kernel, mode="valid")

        # Sliding-window energy of input — same length as corr
        energy   = fftconvolve(np.abs(sym_stream) ** 2, np.ones(N), mode="valid")
        norm_mag = np.abs(corr) / (np.sqrt(energy * N) + 1e-10)

        # Greedy peak picking.
        suppress  = N
        remaining = norm_mag.copy()
        candidates: list[int] = []

        while True:
            idx = int(np.argmax(remaining))
            if remaining[idx] < self.ZC_THRESHOLD:
                break
            candidates.append(idx)
            lo = max(0, idx - suppress)
            hi = min(len(remaining), idx + suppress)
            remaining[lo:hi] = 0.0

        return candidates




    def decode_frame(
        self, sym_stream: np.ndarray, pos: int
    ) -> tuple[int, bytes, int] | None:

        end = pos + self.n_pre + self.frame_syms_with_pilots
        if end > len(sym_stream):
            return None

        frame = sym_stream[pos:end].copy()

        zc_rx   = frame[: self.n_pre]
        product = zc_rx * np.conj(self.preamble_syms)
        phase   = np.angle(np.mean(product))
        frame  *= np.exp(-1j * phase)

        phases   = np.unwrap(np.angle(frame[: self.n_pre] * np.conj(self.preamble_syms)))
        freq_err = float(np.polyfit(np.arange(self.n_pre), phases, 1)[0])
        if abs(freq_err) > 1e-4:
            frame *= np.exp(-1j * freq_err * np.arange(len(frame)))

        pre_power = float(np.mean(np.abs(frame[: self.n_pre]) ** 2))
        frame    *= 1.0 / (math.sqrt(pre_power) + 1e-10)

        # ── Adaptive FIR equalizer ─────────────────────────────────────

        if not hasattr(self, "_eq_taps"):
            NTAPS = 9
            self._eq_taps = np.zeros(NTAPS, dtype=np.complex64)
            self._eq_taps[NTAPS // 2] = 1.0 + 0j
            self._eq_mu = 0.003

        taps = self._eq_taps
        mu   = self._eq_mu
        NTAPS = len(taps)
        mid   = NTAPS // 2

        def _eq_apply(x):
            y = np.zeros_like(x, dtype=np.complex64)
            for n in range(len(x)):
                acc = 0j
                for k in range(NTAPS):
                    idx = n - k
                    if idx >= 0:
                        acc += taps[k] * x[idx]
                y[n] = acc
            return y

        def _eq_train(x, ref):
            for n in range(len(x)):
                acc = 0j
                for k in range(NTAPS):
                    idx = n - k
                    if idx >= 0:
                        acc += taps[k] * x[idx]

                e = ref[n] - acc

                for k in range(NTAPS):
                    idx = n - k
                    if idx >= 0:
                        taps[k] += mu * e * np.conj(x[idx])

        # Train on ZC preamble (strong, known symbols)
        _eq_train(frame[: self.n_pre], self.preamble_syms)

        # Apply equalizer to full frame
        frame = _eq_apply(frame)

        # ── Continue normal processing ─────────────────────────────────

        data_section   = frame[self.n_pre :]
        data_corrected = self._pilot_phase_track(data_section)

        # Optional: light decision-directed refinement on data
        for i in range(len(data_corrected)):
            y = data_corrected[i]

            diffs   = y * math.sqrt(10) - self._const_points
            nearest = self._const_points[np.argmin(np.abs(diffs))]
            target  = nearest / math.sqrt(10)

            e = target - y

            for k in range(NTAPS):
                idx = i - k
                if idx >= 0:
                    taps[k] += (mu * 0.5) * e * np.conj(data_section[idx])

        _zc_quality = float(np.sqrt(pre_power))
        try:
            _scaled  = data_corrected * math.sqrt(10)
            _diffs   = _scaled[:, None] - self._const_points[None, :]
            _nearest = self._const_points[np.argmin(np.abs(_diffs), axis=1)]
            _evm_rms = float(np.sqrt(np.mean(np.abs(_scaled - _nearest) ** 2)))
            _sig_rms = float(np.sqrt(np.mean(np.abs(_nearest) ** 2)))
            _evm_norm = _evm_rms / (_sig_rms + 1e-10)
            _snr_db  = round(-20 * math.log10(_evm_norm + 1e-9), 1)
        except Exception:
            _snr_db, _evm_norm = 0.0, 1.0

        self._last_diag = {
            "snr_evm_db":   _snr_db,
            "evm_pct":      round(_evm_norm * 100, 1),
            "zc_quality":   round(_zc_quality, 3),
            "freq_err_rad": round(abs(freq_err), 6),
        }

        rx_bits = self._symbols_to_bits(data_corrected)
        rx_desc = self._descramble(rx_bits)

        n_bytes  = self.SEQ_BYTES + self.CHUNK_BYTES + self.ECC_BYTES
        rx_bytes = bytes(
            int("".join(map(str, rx_desc[i : i + 8])), 2)
            for i in range(0, n_bytes * 8, 8)
            if i + 8 <= len(rx_desc)
        )

        decoded, err_count, failed = self._rs_decode(rx_bytes)
        if failed or decoded is None:
            return None

        seq_num    = int.from_bytes(decoded[: self.SEQ_BYTES], "big")
        chunk_data = bytes(decoded[self.SEQ_BYTES :])
        return seq_num, chunk_data, err_count

    # ------------------------------------------------------------------
    # Private — phase tracking
    # ------------------------------------------------------------------

    def _pilot_phase_track(self, data_with_pilots: np.ndarray) -> np.ndarray:
        """
        Measure residual phase error at each pilot, interpolate across the
        data section, apply correction, and strip pilot symbols.
        """
        meas_pos: list[int]   = []
        meas_phi: list[float] = []

        for p in self._pilot_positions:
            if p >= len(data_with_pilots):
                break
            rx          = data_with_pilots[p]
            phase_err   = float(np.angle(rx * np.conj(self.PILOT_SYMBOL)))
            meas_pos.append(p)
            meas_phi.append(phase_err)

        if len(meas_phi) < 2:
            return self._strip_pilots(data_with_pilots)

        unwrapped   = np.unwrap(np.array(meas_phi))
        all_pos     = np.arange(len(data_with_pilots))
        phase_curve = np.interp(
            all_pos, meas_pos, unwrapped,
            left=unwrapped[0], right=unwrapped[-1],
        )
        corrected = data_with_pilots * np.exp(-1j * phase_curve)
        return self._strip_pilots(corrected)

    def _strip_pilots(self, mixed: np.ndarray) -> np.ndarray:
        """Remove pilot slots; return data-only symbol array."""
        pilot_set = set(self._pilot_positions)
        return np.array([s for i, s in enumerate(mixed) if i not in pilot_set])

    def _compute_pilot_positions(self) -> list[int]:
        """
        Reproduce the pilot layout from Modulator.insert_pilots().

        Pilot positions in the mixed stream:
            k · (PILOT_INTERVAL + 1)   for  k = 0, 1, 2, …
        """
        positions: list[int] = []
        mixed_idx = 0
        for data_idx in range(self._raw_data_syms):
            if data_idx % self.PILOT_INTERVAL == 0:
                positions.append(mixed_idx)
                mixed_idx += 1  # pilot slot
            mixed_idx += 1      # data slot
        return positions

    # ------------------------------------------------------------------
    # Private — symbol layer
    # ------------------------------------------------------------------

    def _symbols_to_bits(self, symbols: np.ndarray) -> np.ndarray:
        scaled  = symbols * math.sqrt(10)
        diffs   = scaled[:, None] - self._const_points[None, :]
        indices = np.argmin(np.abs(diffs), axis=1)
        bits: list[int] = []
        for idx in indices:
            bits.extend(self._const_keys[idx])
        return np.array(bits)

    def _descramble(self, bits: np.ndarray) -> np.ndarray:
        return (bits ^ self._make_prbs(len(bits))).astype(int)

    def _rs_decode(
        self, encoded_bytes: bytes
    ) -> tuple[bytes | None, int, bool]:
        try:
            decoded, _, errata = self.rsc.decode(encoded_bytes)
            count = errata if isinstance(errata, int) else len(errata)
            return bytes(decoded), count, False
        except Exception:
            return None, self.ECC_BYTES // 2, True

    def _make_prbs(self, length: int) -> np.ndarray:
        state = self.PRBS_SEED
        bits  = np.zeros(length, dtype=int)
        for i in range(length):
            bit     = ((state >> 15) ^ (state >> 14) ^ (state >> 12) ^ (state >> 3)) & 1
            bits[i] = (state >> 15) & 1
            state   = ((state << 1) | bit) & 0xFFFF
        return bits

    def _reassemble(self) -> str:
        if not self.received:
            return ""
        n   = max(self.received) + 1
        raw = b"".join(
            self.received.get(i, b"\x00" * self.CHUNK_BYTES)
            for i in range(n)
        )
        return raw.rstrip(b"\x00").decode("utf-8", errors="replace")

    # ------------------------------------------------------------------
    # Stats emission
    # ------------------------------------------------------------------

    def _emit_frame_stat(self, seq: int, err_count: int,
                         agc_gain_db: float = 0.0,
                         input_rms_db: float = -60.0) -> None:
        import json as _json
        ecc_capacity     = self.ECC_BYTES // 2
        ecc_headroom     = max(0, ecc_capacity - err_count)
        ecc_headroom_pct = round(100 * ecc_headroom / max(ecc_capacity, 1))
        diag = self._last_diag  # set by decode_frame
        stat = {
            "seq":              seq,
            "err_count":        err_count,
            "ecc_capacity":     ecc_capacity,
            "ecc_headroom":     ecc_headroom,
            "ecc_headroom_pct": ecc_headroom_pct,
            "snr_evm_db":       diag.get("snr_evm_db",   0.0),
            "evm_pct":          diag.get("evm_pct",     100.0),
            "zc_quality":       diag.get("zc_quality",    0.0),
            "freq_err_rad":     diag.get("freq_err_rad",  0.0),
            "agc_gain_db":      agc_gain_db,
            "input_rms_db":     input_rms_db,
            "net_bps":          self.net_bps,
            "coded_bps":        self.coded_bps,
            "gross_bps":        self.gross_bps,
        }
        self._frame_stats.append(stat)
        print(f"FRAME_STAT:{_json.dumps(stat)}", flush=True)

    def _write_stats(self) -> None:
        import json as _json
        summary = {
            "frames": self._frame_stats,
            "net_bps": self.net_bps, "coded_bps": self.coded_bps,
            "gross_bps": self.gross_bps,
            "total_decoded": len(self._frame_stats),
        }
        with open(self._stats_out, "w") as f:
            _json.dump(summary, f, indent=2)

    # ------------------------------------------------------------------
    # Static helpers — shared logic with Modulator
    # ------------------------------------------------------------------

    @staticmethod
    def _make_zadoff_chu(length: int = 63, root: int = 25) -> np.ndarray:
        n = np.arange(length)
        return np.exp(-1j * np.pi * root * n * (n + 1) / length)

    @staticmethod
    def _rrc_filter(beta: float, span: int, sps: int) -> np.ndarray:
        N = span * sps
        if N % 2 == 0:
            N += 1
        t = np.arange(-(N - 1) / 2, (N - 1) / 2 + 1) / float(sps)
        h = np.zeros(len(t))
        for i, ti in enumerate(t):
            if ti == 0.0:
                h[i] = 1.0 - beta + (4.0 * beta / np.pi)
            elif abs(abs(ti) - 1.0 / (2.0 * beta)) < 1e-6:
                h[i] = (beta / np.sqrt(2.0)) * (
                    (1.0 + 2.0 / np.pi) * np.sin(np.pi / (4.0 * beta))
                  + (1.0 - 2.0 / np.pi) * np.cos(np.pi / (4.0 * beta))
                )
            elif abs(abs(ti) - 1.0 / (4.0 * beta)) < 1e-6:
                ti2  = ti + 1e-7
                h[i] = (
                    np.sin(np.pi * ti2 * (1.0 - beta))
                    + 4.0 * beta * ti2 * np.cos(np.pi * ti2 * (1.0 + beta))
                ) / (np.pi * ti2 * (1.0 - (4.0 * beta * ti2) ** 2))
            else:
                h[i] = (
                    np.sin(np.pi * ti * (1.0 - beta))
                    + 4.0 * beta * ti * np.cos(np.pi * ti * (1.0 + beta))
                ) / (np.pi * ti * (1.0 - (4.0 * beta * ti) ** 2))
        h /= np.sqrt(np.sum(h ** 2))
        return h


